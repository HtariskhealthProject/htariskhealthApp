function makeReading(
  id: string,
  patientId: string,
  userId: string,
  systolic: number,
  diastolic: number,
  heartRate: number,
  context: BloodPressureReading['reading_context'],
  method: BloodPressureReading['reading_method'],
  arm: BloodPressureReading['arm'],
  position: BloodPressureReading['position'],
  symptoms: AlarmSymptom[],
  notes: string,
  createdAt: string
): BloodPressureReading {
  const classification = classifyBloodPressure(systolic, diastolic, symptoms);
  return {
    id,
    patient_id: patientId,
    user_id: userId,
    systolic,
    diastolic,
    heart_rate: heartRate,
    mean_arterial_pressure: calculateMeanArterialPressure(systolic, diastolic),
    reading_context: context,
    reading_method: method,
    arm,
    position,
    alarm_symptoms: symptoms,
    category: classification.category,
    risk_level: classification.riskLevel,
    notes,
    created_at: createdAt,
  };
}

